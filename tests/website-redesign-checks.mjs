import assert from 'node:assert/strict';
export async function verifyRedesign(page, { initialize, state, check, outputPath, url, noOverflow }) {
    const seek = async (p) => { await page.evaluate(p => { const e = document.querySelector('.experience-scroll'); scrollTo({ top: e.getBoundingClientRect().top + scrollY + (e.offsetHeight - document.querySelector('.experience-sticky').offsetHeight) * p, behavior: 'instant' }); }, p); await page.waitForFunction(p => { const d = window.websiteDemo.diagnostics.experience.intro; return Math.abs(d.progress - p) < .003 && !d.animating; }, p); };
    await page.evaluate(() => { const e = document.querySelector('.experience-scroll'); scrollTo({ top: e.getBoundingClientRect().top + scrollY - innerHeight * 1.2, behavior: 'instant' }); });
    await page.waitForTimeout(150);
    await page.evaluate(() => { const e = document.querySelector('.experience-scroll'); scrollTo({ top: e.getBoundingClientRect().top + scrollY - innerHeight * .78, behavior: 'instant' }); });
    const entryY = await page.evaluate(() => scrollY);
    await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return d.typed[0] > 0 && d.typed[0] < 1; });
    assert.equal(await page.locator('.experience-era').evaluate(el => getComputedStyle(el).opacity), '0');
    await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return d.typed.every(n => n === 1) && !d.animating; });
    assert.equal(await page.evaluate(() => scrollY), entryY, 'Entry typing proceeds without waiting for a full-screen scroll');
    assert.deepEqual(await page.locator('.experience-typed').allTextContents(), ['เบื้องหลังความสมบูรณ์แบบ', 'ของโครงการชั้นนำ']);
    const originalYear = await page.locator('.experience-era strong').elementHandle();
    const originalRing = await page.locator('.experience-ring').first().elementHandle();
    const originalPhoto = await page.locator('.experience-pile-photo').first().elementHandle();
    const originalCounter = await page.locator('.experience-counter strong').elementHandle();
    await seek(.22);
    assert.equal(await originalYear.innerText(), '2005');
    assert.equal(await page.locator('.experience-era').evaluate(el => getComputedStyle(el).opacity), '1');
    await seek(.43);
    await page.waitForFunction(() => [...document.querySelectorAll('.experience-pile-photo img')].every(img => img.complete && img.naturalWidth > 0));
    assert.ok(await originalRing.evaluate(el => el.getBoundingClientRect().width) > 145, 'The main dashboard gauge is large');
    const pile = await page.locator('.experience-pile-photo[data-story="0"]').evaluateAll(photos => { const r = photos.map(p => p.getBoundingClientRect()); return { large: r.every(p => p.width > 220), overlap: r.every((p, i) => r.some((q, j) => i !== j && Math.min(p.right, q.right) > Math.max(p.left, q.left) + 35)) }; });
    assert.ok(pile.large && pile.overlap, 'Large photographs pile together on the right');
    await page.screenshot({ path: outputPath('redesign-large-experience.png') });
    const smallCounterSize = await originalCounter.evaluate(el => parseFloat(getComputedStyle(el).fontSize));
    for (const [index, position] of [.46, .68, .9].entries()) {
        await seek(position);
        const frame = (await state()).experience.intro;
        assert.equal(frame.rings[index], 1, 'Each ring finishes while it is still large');
        assert.equal(frame.archived[index], 0, 'Completed circles and photos have a resting interval');
        assert.deepEqual(frame.photos.slice(index * 3, index * 3 + 3), [1, 1, 1]);
        assert.equal(Number(await page.locator('.experience-ring-arc').nth(index).evaluate(el => el.style.strokeDashoffset)), 0);
    }
    await seek(.64);
    assert.deepEqual((await state()).experience.intro.archived, [1, 0, 0]);
    assert.equal(await page.locator('.experience-pile-photo[data-story="0"]').evaluateAll(items => items.every(el => getComputedStyle(el).opacity === '1')), true);
    await page.locator('.experience-scene-footer a[href="#experience-evidence"]').click();
    await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return d.gather === 1 && d.proof === 1 && !d.animating; });
    assert.deepEqual((await state()).experience.intro.counters, [21, 175000, 10]);
    assert.equal(await originalCounter.innerText(), '175,000');
    assert.ok(await originalCounter.evaluate(el => parseFloat(getComputedStyle(el).fontSize)) > smallCounterSize * 2);
    assert.equal(await page.locator('.experience-dashboard-heading').evaluate(el => getComputedStyle(el).opacity), '0');
    assert.equal((await state()).experience.intro.gather, 1);
    assert.equal(await originalRing.evaluate(el => el.isConnected && el === document.querySelector('.experience-ring')), true);
    assert.equal(await originalPhoto.evaluate(el => el.isConnected && el === document.querySelector('.experience-pile-photo')), true);
    const dashboardBounds = await page.evaluate(() => [...document.querySelectorAll('.experience-ring')].every((ring, i) => { const r = ring.getBoundingClientRect(), slot = document.querySelectorAll('.experience-summary-slot')[i].getBoundingClientRect(); return r.left >= slot.left - 1 && r.right <= slot.right + 1 && r.top >= slot.top - 1 && r.bottom <= slot.bottom + 1; }));
    assert.ok(dashboardBounds, 'The same gauges collect inside the final dashboard cards');
    assert.equal(await page.locator('.experience-checks li.is-checked').count(), 4);
    await page.waitForFunction(() => window.websiteDemo.diagnostics.experience.intro.marqueeRunning);
    await page.locator('.experience-projects-toggle').click();
    assert.equal((await state()).experience.intro.marqueeRunning, false);
    await page.locator('.experience-projects-toggle').click();
    await page.screenshot({ path: outputPath('redesign-collected-dashboard.png') });
    await seek(.43);
    assert.equal((await state()).experience.intro.gather, 0);
    assert.equal((await state()).experience.intro.archived[0], 0);
    assert.ok(await originalRing.evaluate(el => el.getBoundingClientRect().width) > 145);
    check('Entry types from zero before the year appears; large gauges and three-photo piles archive and collect as the same DOM nodes into a framed dashboard, with reversible scroll and working project names.');
    check('All three gauges and photo piles finish before docking; the same area counter grows into the final 175,000 headline.');
    await page.setViewportSize({ width: 1920, height: 900 });
    await page.locator('#collections').evaluate(e => e.scrollIntoView({ behavior: 'instant' }));
    assert.equal(await page.locator('.collections-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length), 5, 'Desktop catalogue has five compact product cards per row');
    await page.setViewportSize({ width: 1122, height: 900 });
    await page.locator('[data-family="all"]').click();
    assert.equal((await state()).collections.visible, 14);
    await page.locator('[data-family="spc"]').click();
    await page.locator('[data-family="herringbone"]').click();
    await page.locator('#collection-thickness').selectOption('5');
    assert.equal((await state()).collections.visible, 3);
    await page.locator('[data-family="glue"]').click();
    assert.equal((await state()).collections.visible, 0);
    assert.equal(await page.locator('.collection-empty').count(), 1);
    await page.locator('[data-family="all"]').click();
    await page.locator('#collection-size').selectOption('188 × 590');
    assert.equal((await state()).collections.visible, 1);
    await page.locator('[data-family="all"]').click();
    await page.locator('[data-series="laminate-8"] .collection-estimate').click();
    assert.equal((await state()).pricing.rowIndex, 8);
    await page.locator('#estimate-sqm').fill('30');
    assert.equal((await state()).pricing.total, 25000);
    assert.equal(await page.locator('#price-table,#pricing-rates').count(), 0);
    const order = await page.evaluate(() => document.querySelector('#package-specs').contains(document.querySelector('#estimate-form')) && !!(document.querySelector('#estimate-calculator').compareDocumentPosition(document.querySelector('.pricing-package-stage')) & Node.DOCUMENT_POSITION_FOLLOWING));
    assert.ok(order, 'Spec selection and estimation share one desk, above packages');
    await page.locator('[data-spec-row="11"]').click();
    assert.equal((await state()).pricing.total, 35200);
    await page.locator('[data-spec-pattern="straight"]').click();
    assert.equal((await state()).pricing.spec.family, 'laminate');
    await page.locator('[data-spec-family="spc"]').click();
    await page.locator('[data-spec-row="1"]').click();
    await page.locator('#package-size').selectOption('spc-5-188');
    assert.equal((await state()).pricing.spec.sizeMm, '188 × 590');
    await page.locator('[data-spec-row="0"]').click();
    const noFoam = (await state()).pricing.total;
    await page.locator('[data-spec-foam="true"]').click();
    assert.equal((await state()).pricing.total, noFoam);
    assert.equal((await state()).pricing.spec.foam, true);
    await page.locator('[data-spec-pattern="herringbone"]').click();
    await page.locator('[data-spec-shade="1"]').click();
    assert.equal((await state()).pricing.total, 30700);
    const selected = (await state()).pricing.spec;
    assert.equal(await page.locator('#package-model-texture').getAttribute('src'), selected.image);
    await page.locator('#estimate-prep input[value="skim"]').check();
    assert.equal((await state()).pricing.total, 35200);
    await page.locator('#estimate-prep input[value="skim"]').uncheck();
    await page.locator('#estimate-night').check();
    assert.equal((await state()).pricing.total, 34200);
    await page.locator('#estimate-night').uncheck();
    await page.locator('#estimate-form [data-contact-open]').click();
    assert.ok((await page.locator('#contact-selection').innerText()).includes(selected.code));
    await page.keyboard.press('Escape');
    await page.locator('.packages-cta').first().click();
    assert.ok((await page.locator('#contact-selection').innerText()).includes(selected.code));
    await page.keyboard.press('Escape');
    await page.locator('[data-spec-family="lvt"]').click();
    await page.locator('[data-spec-row="7"]').click();
    assert.equal((await state()).pricing.total, 19900);
    assert.equal((await state()).pricing.spec.foam, false);
    assert.equal(await page.locator('.package-foam-field').isVisible(), false);
    await page.locator('[data-spec-family="spc"]').click();
    await page.locator('[data-spec-row="1"]').click();
    await page.locator('#package-specs').evaluate(el => el.scrollIntoView({ behavior: 'instant', block: 'start' }));
    await page.waitForFunction(() => { const s = window.websiteDemo.diagnostics.pricing.spec; return s.modelReady && document.querySelector('.package-model-canvas').dataset.renderedTexture === s.image; });
    const model = page.locator('.package-model-canvas canvas');
    const before = await model.screenshot();
    const box = await model.boundingBox();
    await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .7, box.y + box.height * .6, { steps: 10 });
    await page.mouse.up();
    assert.notDeepEqual(await model.screenshot(), before, 'The real 3D material sample rotates with a mouse drag');
    await page.screenshot({ path: outputPath('redesign-estimate-3d.png') });
    await page.waitForFunction(() => {
        const room = document.querySelector('.package-room');
        const spec = window.websiteDemo.diagnostics.pricing.spec;
        return room?.dataset.renderedTexture === spec.image && room.dataset.renderedRoom === '0';
    });
    assert.equal(await page.locator('[data-spec-room]').count(), 7);
    const mainPreview = (await state()).preview;
    const roomPixels = () => page.locator('.package-room-view canvas').evaluate(canvas => {
        const ctx = canvas.getContext('2d'), pixels = ctx.getImageData(0, 0, canvas.width, canvas.height).data;
        let upper = 2166136261, whole = 2166136261;
        const limit = Math.floor(canvas.height * .24) * canvas.width * 4;
        for (let i = 0; i < pixels.length; i += 32) {
            whole = Math.imul(whole ^ pixels[i] ^ pixels[i + 1] ^ pixels[i + 2], 16777619);
            if (i < limit) upper = Math.imul(upper ^ pixels[i] ^ pixels[i + 1] ^ pixels[i + 2], 16777619);
        }
        return { upper: upper >>> 0, whole: whole >>> 0 };
    });
    await page.locator('[data-spec-room="1"]').click();
    await page.waitForFunction(() => document.querySelector('.package-room').dataset.renderedRoom === '1');
    const bedroom = await roomPixels();
    const unchangedPrice = (await state()).pricing.total;
    await page.locator('[data-spec-shade="2"]').click();
    await page.waitForFunction(() => document.querySelector('.package-room').dataset.renderedTexture === window.websiteDemo.diagnostics.pricing.spec.image);
    const darkBedroom = await roomPixels();
    assert.notEqual(darkBedroom.whole, bedroom.whole, 'The selected catalogue shade changes real room pixels');
    assert.equal(darkBedroom.upper, bedroom.upper, 'The room ceiling and furniture above the floor stay intact');
    assert.equal((await state()).pricing.total, unchangedPrice, 'Room and shade selection do not invent a new price');
    await page.locator('[data-spec-pattern="herringbone"]').click();
    await page.waitForFunction(() => document.querySelector('.package-room').dataset.cataloguePattern === 'herringbone' && document.querySelector('.package-room').dataset.renderedTexture === window.websiteDemo.diagnostics.pricing.spec.image);
    assert.notEqual((await roomPixels()).whole, darkBedroom.whole, 'The sample room also follows the selected lay-up');
    await page.locator('[data-spec-room="2"]').click();
    await page.waitForFunction(() => document.querySelector('.package-room').dataset.renderedRoom === '2');
    assert.equal((await state()).preview.room, mainPreview.room);
    assert.equal((await state()).preview.finish, mainPreview.finish);
    assert.equal((await state()).preview.pattern, mainPreview.pattern, 'Estimator room selection stays separate from the main visualizer');
    await page.screenshot({ path: outputPath('compact-spec-room-preview.png') });
    await page.locator('#package-specs').evaluate(el => scrollTo({ top: el.getBoundingClientRect().top + scrollY + 260, behavior: 'instant' }));
    const columnTops = () => page.evaluate(() => ['.package-preview-stack', '.package-spec-controls', '.package-estimate-slot'].map(selector => document.querySelector(selector).getBoundingClientRect().top));
    const beforeScroll = await columnTops();
    await page.mouse.move(1100, 450);
    await page.mouse.wheel(0, 180);
    await page.waitForTimeout(250);
    const afterScroll = await columnTops();
    const deltas = afterScroll.map((top, index) => top - beforeScroll[index]);
    assert.ok(deltas.every(delta => delta < -100 && Math.abs(delta - deltas[0]) < 2), 'All estimator columns move together');
    check('Material/room preview, specification controls and price move together without a pinned left column.');
    check('Estimator rooms follow actual catalogue shades and lay-up, retain the room above the floor, and do not change prices or the independent main visualizer.');
    check('The horizontal multi-filter covers all catalogue sizes and every price row; a complete visual spec picker and draggable 3D sample share the live estimator, preserve fee arithmetic and carry selections into quote/package enquiries.');
    for (const viewport of [{ width: 622, height: 532 }, { width: 844, height: 390 }]) {
        await page.setViewportSize(viewport);
        const anchored = new URL(url);
        anchored.searchParams.set('redesign-window', `${viewport.width}x${viewport.height}`);
        anchored.hash = 'experience-intro';
        await initialize(anchored.href);
        const travel = await page.evaluate(() => { const e = document.querySelector('.experience-scroll'); scrollTo({ top: e.getBoundingClientRect().top + scrollY, behavior: 'instant' }); return e.offsetHeight - document.querySelector('.experience-sticky').offsetHeight; });
        await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return d.mode === 'scroll' && d.progress < .005 && !d.animating; });
        await page.mouse.move(viewport.width / 2, viewport.height / 2);
        await page.mouse.wheel(0, travel * .43);
        await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return Math.abs(d.progress - .43) < .01 && !d.animating; });
        assert.ok((await state()).experience.intro.counters[0] > 0);
        await page.mouse.wheel(0, travel * .21);
        await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return Math.abs(d.progress - .64) < .01 && !d.animating; });
        assert.equal((await state()).experience.intro.archived[0], 1);
        await page.mouse.wheel(0, travel * .37);
        await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return d.gather === 1 && !d.animating; });
        assert.equal((await state()).experience.intro.counter, 175000);
        assert.equal(await page.locator('.experience-checks li.is-checked').count(), 4);
        await page.screenshot({ path: outputPath(`redesign-summary-${viewport.width}x${viewport.height}.png`) });
        await page.mouse.wheel(0, -travel * .58);
        await page.waitForFunction(() => { const d = window.websiteDemo.diagnostics.experience.intro; return d.active === 0 && d.gather === 0 && d.progress < .49 && !d.animating; });
        await noOverflow();
    }
    check('Real wheel input animates and reverses the complete timeline and collected dashboard in short in-app and landscape windows.');
    await page.setViewportSize({ width: 1122, height: 900 });
    await initialize();
}
