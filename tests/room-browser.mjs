import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const base = process.env.ROOM_TEST_URL || 'http://127.0.0.1:5173/room/';
const out = new URL('../test-results/room/',import.meta.url);
await mkdir(out,{recursive:true});
const path = name => fileURLToPath(new URL(name,out));
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page = await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors = [];
const checks = [];
const samples = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if(message.type()==='error') errors.push(message.text()); });
const capture = async (progress, name) => {
  await page.evaluate(value=>window.roomDemo.setProgress(value),progress);
  await page.waitForTimeout(150);
  samples.push(await page.evaluate(()=>window.roomDemo.diagnostics));
  await page.screenshot({path:path(name)});
};
try {
  await page.goto(base,{waitUntil:'networkidle'});
  await page.evaluate(()=>window.roomDemo.ready);
  assert.equal(await page.evaluate(()=>window.roomDemo.diagnostics.webgl),true);
  assert.equal(await page.locator('[data-finish]').count(),6);
  await capture(0,'room-desktop.png');
  for (const [progress,name] of [[.31,'room-outgoing.png'],[.49,'room-subfloor.png'],[.69,'room-incoming.png'],[1,'room-finish-2.png'],[2,'room-finish-3.png'],[3,'room-finish-4.png'],[4,'room-finish-5.png'],[5,'room-finish-6.png']]) await capture(progress,name);
  for(let index=0;index<6;index++) {
    await page.evaluate(value=>window.roomDemo.setProgress(value),index);
    await page.waitForTimeout(35);
    assert.equal(await page.locator('#finish-name').innerText(),`พื้นปก${index+1}`);
    assert.equal(await page.locator('[data-finish][aria-pressed="true"]').count(),1);
  }
  checks.push('Six real instanced floors render in the requested order with exactly one selected swatch.');
  await capture(.31,'room-reverse.png');
  const repeated = samples.at(-1);
  assert.deepEqual(repeated.floor,samples[1].floor);
  assert.equal(repeated.triangles,samples[1].triangles);
  assert.equal(repeated.memory.textures,samples.at(-2).memory.textures);
  checks.push('Reverse sampling returns to identical scene state; finish switching retains stable GPU allocations.');
  await page.locator('#reference-toggle').click();
  await page.waitForFunction(()=>document.querySelector('#reference-image').naturalWidth>0);
  await page.screenshot({path:path('room-reference.png')});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#reference-panel').isVisible(),false);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'reference-toggle');
  checks.push('Original reference loads on demand; Escape closes it and restores focus.');
  await page.locator('[data-finish="floor-06"]').click();
  await page.waitForFunction(()=>window.roomDemo.diagnostics.position>4.999,{timeout:10000});
  assert.equal(await page.locator('#finish-name').innerText(),'พื้นปก6');
  await page.locator('#motion-toggle').click();
  const frozen = await page.evaluate(()=>window.roomDemo.diagnostics.position);
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(()=>window.roomDemo.diagnostics.position),frozen);
  await page.locator('#motion-toggle').click();
  await page.waitForFunction(()=>window.roomDemo.diagnostics.position<.001);
  await page.mouse.wheel(0,600);
  await page.waitForFunction(()=>window.roomDemo.diagnostics.position>.5);
  assert.ok(await page.evaluate(()=>window.roomDemo.diagnostics.position<1));
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.waitForFunction(()=>window.roomDemo.diagnostics.position<.001);
  checks.push('Swatches drive native scroll; pause freezes the story and resume follows current scroll.');
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  await capture(0,'room-mobile.png');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  await capture(.69,'room-mobile-incoming.png');
  await page.emulateMedia({reducedMotion:'reduce'});
  await capture(2.6,'room-reduced-motion.png');
  const reduced = await page.evaluate(()=>window.roomDemo.diagnostics);
  assert.deepEqual(reduced.floor.visibleFinishes,['floor-04']);
  checks.push('390px mobile layout has no horizontal overflow; reduced motion displays one installed finish.');
  for (const value of [4,4.3]) {
    await page.evaluate(value=>window.scrollTo({top:value/5*(document.querySelector('#room-story').offsetHeight-document.querySelector('#room-canvas').clientHeight),behavior:'instant'}),value);
    await page.waitForTimeout(80);
    const progress = await page.locator('#story-progress').evaluate(element=>parseFloat(element.style.width));
    assert.ok(Math.abs(progress-value/5*100)<.1,'reduced-motion progress tracks scroll within the same finish');
  }
  await page.setViewportSize({width:844,height:390});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.waitForTimeout(200);
  const tray = await page.locator('#finish-picker').boundingBox();
  assert.ok(tray.y>=0 && tray.y+tray.height<=390,'landscape swatches must remain inside the viewport');
  await page.screenshot({path:path('room-landscape.png')});
  checks.push('Reduced-motion progress remains live; landscape swatches fit an 844×390 viewport.');
  await page.evaluate(()=>window.roomDemo.dispose());
  assert.equal(await page.locator('#room-canvas canvas').count(),0);
  checks.push('Disposal releases renderer and removes canvas.');
  const early = await browser.newPage();
  early.on('pageerror',error=>errors.push(error.message));
  await early.goto(base,{waitUntil:'domcontentloaded'});
  await early.evaluate(()=>window.roomDemo.dispose());
  await early.waitForTimeout(350);
  assert.equal(await early.locator('#room-canvas canvas').count(),0);
  assert.equal(await early.evaluate(()=>window.roomDemo.diagnostics.ready),false);
  await early.close();
  checks.push('Disposing during asynchronous initialization cannot resurrect the scene.');
  const fallback = await browser.newPage();
  fallback.on('pageerror',error=>errors.push(error.message));
  await fallback.addInitScript(()=>{
    const original=HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext=function(type,...args){return type==='webgl2'?null:original.call(this,type,...args);};
  });
  await fallback.goto(base,{waitUntil:'networkidle'});
  await fallback.evaluate(()=>window.roomDemo.ready);
  assert.equal(await fallback.evaluate(()=>window.roomDemo.diagnostics.fallback),true);
  assert.equal(await fallback.locator('#motion-toggle').isDisabled(),true);
  await fallback.locator('[data-finish="floor-05"]').click();
  await fallback.waitForFunction(()=>window.roomDemo.diagnostics.selected===4);
  assert.match(await fallback.locator('#room-canvas').getAttribute('style'),/floor-05.png/);
  await fallback.screenshot({path:path('room-fallback.png')});
  await fallback.close();
  checks.push('Without WebGL, the supplied references replace the scene and all six swatches still work.');
  assert.deepEqual(errors,[]);
  await writeFile(path('report.json'),JSON.stringify({checks,errors,samples},null,2));
  console.log(JSON.stringify({checks,errors,samples:samples.map(s=>({position:s.position,calls:s.calls,triangles:s.triangles,memory:s.memory,motionFps:s.motionFps}))},null,2));
} finally {
  await writeFile(path('last-run.json'),JSON.stringify({checks,errors,samples},null,2));
  await browser.close();
}
